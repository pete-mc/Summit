/*
 * `solo flat` (set on the template) drops the underline and default box-shadow.
 *
 * Every rule below targeting a nested Vuetify-internal element (.v-input__control,
 * .v-input__slot, .v-select__selection, .v-icon, the raw <input>) uses ::v-deep. Vue 2's scoped
 * CSS only stamps its data-v-* attribute onto elements THIS component's own template literally
 * writes — v-select/v-text-field's root element gets it (since it's written here), but their
 * internal render output (.v-input__slot etc.) is generated by Vuetify's own render function, not
 * by this template, so it never receives the attribute. A plain scoped selector like
 * `.oas-vue-column-filter-input .v-input__slot` compiles to `...[data-v-xxx] .v-input__slot`
 * (the attribute lands on the rightmost matched element only when that element is one we wrote),
 * which can never match a Vuetify-internal descendant — confirmed live: the class showed up
 * nowhere in DevTools' Styles panel for the inner elements at all. ::v-deep drops the scoping
 * attribute from that point in the selector onward, letting these rules reach in.
 *
 * Both the v-text-field input AND the v-select selected-value text are forced to 20px by global
 * rules this page doesn't control:
 *   `.v-application .theme--light.v-text-field input { font-size: 20px; }`
 *   `.v-application .v-select__selection--comma { font-size: 20px; line-height: 1.5rem; ... }`
 * (both confirmed via live DevTools Computed panel — an earlier attempt wrongly assumed the
 * v-select rule didn't exist because only the EMPTY/placeholder state had been checked; once a
 * value is actually selected, `.v-select__selection--comma` is the element that renders it, and
 * that's what the second rule targets). Both are overridden below with !important, since neither
 * global rule is itself !important-qualified.
 */
.oas-vue-column-filter-input ::v-deep .v-input__control,
.oas-vue-column-filter-input ::v-deep .v-input__slot {
  min-height: 30px !important;
  box-shadow: none !important;
}

